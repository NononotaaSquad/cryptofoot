import pluginNext from "@next/eslint-plugin-next";
import pluginReactHooks from "eslint-plugin-react-hooks";
import { globalIgnores } from "eslint/config";
import globals from "globals";

import { createBaseConfig } from "./base.js";

/**
 * ESLint configuration for the Next.js app.
 *
 * @param {string} tsconfigRootDir pass `import.meta.dirname`
 */
export const createNextConfig = (tsconfigRootDir) =>
  createBaseConfig(tsconfigRootDir, [
    globalIgnores([
      // Default ignores of eslint-config-next:
      ".next/**",
      "out/**",
      "build/**",
      "next-env.d.ts",
      // Generated by Orval (`npm run api:gen`):
      "lib/api/generated/**",
    ]),
    {
      languageOptions: {
        globals: {
          ...globals.browser,
          ...globals.serviceworker,
        },
      },
    },
    pluginNext.configs.recommended,
    pluginNext.configs["core-web-vitals"],
    pluginReactHooks.configs.flat.recommended,
    {
      // All backend calls go through the generated client; lib/api/client.ts
      // is the only hand-written fetch.
      files: ["**/*.{ts,tsx}"],
      ignores: ["lib/api/**"],
      rules: {
        "no-restricted-globals": [
          "error",
          {
            name: "fetch",
            message:
              "Use the generated API client from @/lib/api instead of fetch.",
          },
        ],
        "no-restricted-properties": [
          "error",
          ...["globalThis", "window", "self"].map((object) => ({
            object,
            property: "fetch",
            message:
              "Use the generated API client from @/lib/api instead of fetch.",
          })),
        ],
      },
    },
  ]);
